# по т. Пифагора находим расстояние между точкой и центром окружности и сравниваем с радиусом
xc = int(input("xc = "))
yc = int(input("yc = "))
r = int(input("r = "))
x = int(input("x = "))
y = int(input("y = "))
s = (x - xc)**2 + (y - yc)**2
d = r**2
if s > d:
    print("Точка вне окружности")
elif s == d:
    print("Точка лежит на окружности")
else:
    print("точка внутри окружности")